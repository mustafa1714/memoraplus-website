"""Builds web derivatives of the company's project images.

Usage: python -I process_images.py <originals_dir> <public_projects_dir> <media_ts_path>

For every <slug>/<name>.<ext> original: auto-orient, convert to sRGB/RGB, resize (never upscale) to
640/1280/1920 px wide, save WebP (q=74) as <public>/<slug>/<name>-<w>.webp, and write a TypeScript
manifest with each image's base path, available widths and intrinsic size.
Files named "plan.*" are site plans: kept larger (1280/2400) and listed separately.
"""
import json
import sys
from pathlib import Path

from PIL import Image, ImageOps

Image.MAX_IMAGE_PIXELS = None  # trusted, company-supplied renders can exceed the default bomb limit

src, dst, ts = map(Path, sys.argv[1:4])
manifest = {}
total = 0
for project in sorted(p for p in src.iterdir() if p.is_dir()):
    entry = {"gallery": [], "plans": []}
    for f in sorted(project.iterdir()):
        if f.suffix.lower() not in {".jpg", ".jpeg", ".png", ".tif", ".tiff"}:
            continue
        is_plan = f.stem == "plan"
        with Image.open(f) as im:
            im = ImageOps.exif_transpose(im)
            if im.mode not in ("RGB",):
                im = im.convert("RGBA").convert("RGB") if "A" in im.mode or im.mode == "P" else im.convert("RGB")
            w0, h0 = im.size
            widths = [1280, 2400] if is_plan else [640, 1280, 1920]
            out_dir = dst / project.name
            out_dir.mkdir(parents=True, exist_ok=True)
            made = []
            for w in widths:
                tw = min(w, w0)  # no upscaling: a small original is also kept at its own width
                if tw in made:
                    continue
                th = round(h0 * tw / w0)
                im2 = im.resize((tw, th), Image.LANCZOS) if tw != w0 else im
                out = out_dir / f"{f.stem}-{tw}.webp"
                im2.save(out, "WEBP", quality=74, method=6)
                total += out.stat().st_size
                made.append(tw)
            largest = max(made)
            rec = {"src": f"/projects/{project.name}/{f.stem}", "widths": made, "w": largest, "h": round(h0 * largest / w0)}
            (entry["plans"] if is_plan else entry["gallery"]).append(rec)
            print(f"{project.name}/{f.name}: {w0}x{h0} -> {made}")
    manifest[project.name] = entry

ts.write_text(
    "// GENERATED by process_images.py from the company's Google Drive originals — do not edit by hand.\n"
    "// Each image exists as `${src}-${width}.webp` for every width in `widths`.\n"
    "export type MediaImage = { src: string; widths: number[]; w: number; h: number };\n"
    "export const PROJECT_MEDIA: Record<string, { gallery: MediaImage[]; plans: MediaImage[] }> = "
    + json.dumps(manifest, indent=2, ensure_ascii=False)
    + ";\n",
    encoding="utf-8",
)
print(f"TOTAL webp bytes: {total:,}")
